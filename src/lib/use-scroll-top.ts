"use client"

import { useEffect } from "react"

/**
 * Прокрутка страницы наверх при смене режима экрана (`key`): пустой экран →
 * сцена → галерея результатов. Иначе после «Перенести»/«Построить» новая
 * карточка встаёт в голову списка, а экран остаётся прокрученным туда, где
 * была сцена или полоса «Добавить…», и кажется, что ничего не произошло;
 * а новый исходник, приложенный из глубины галереи, открывался бы за кадром.
 * Мгновенно, не плавно: плавную прокрутку обрывает перестройка страницы.
 */
export function useScrollTopOnChange(key: unknown): void {
  useEffect(() => {
    window.scrollTo(0, 0)
  }, [key])
}
